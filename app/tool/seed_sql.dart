// Generates supabase/seed/10_catalog.sql from the Dart demo catalog, so the
// database seed and the app's in-memory demo data come from one source.
//
//   cd app && dart run tool/seed_sql.dart ../supabase/seed/10_catalog.sql
//
// test/tool/seed_sql_test.dart fails when the committed file is out of date.
import 'dart:io';

import 'package:zaba/features/catalog/data/demo_catalog.dart';
import 'package:zaba/features/catalog/domain/allergen.dart';

String _text(String value) => "'${value.replaceAll("'", "''")}'";

String _allergens(Set<Allergen> allergens) {
  if (allergens.isEmpty) return "'{}'::text[]";
  final sorted = allergens.toList()..sort((a, b) => a.index.compareTo(b.index));
  return 'array[${sorted.map((a) => _text(a.code)).join(', ')}]::text[]';
}

String catalogSeedSql() {
  final out = StringBuffer()
    ..writeln('-- GENERATED by `dart run tool/seed_sql.dart` from')
    ..writeln(
      '-- app/lib/features/catalog/data/demo_catalog.dart. Do not edit by hand.',
    )
    ..writeln('--')
    ..writeln(
      '-- Made-up demo menu. Prices are gross (VAT included), in whole forints.',
    )
    ..writeln(
      '-- Allergens and the VAT rate are illustrative and must be confirmed with an',
    )
    ..writeln('-- accountant before real use.')
    ..writeln()
    ..writeln(
      'insert into public.categories (id, name, icon_key, sort_order) values',
    );

  final categories = [
    for (var i = 0; i < demoCategories.length; i++)
      '  (${_text(demoCategories[i].id)}, ${_text(demoCategories[i].name)}, '
          '${_text(demoCategories[i].iconKey)}, ${i + 1})',
  ];
  out
    ..writeln('${categories.join(',\n')};')
    ..writeln()
    ..writeln(
      'insert into public.products '
      '(id, category_id, name, description, allergens, vegetarian, popularity, image_path) values',
    );

  final products = [
    for (final p in demoProducts)
      '  (${_text(p.id)}, ${_text(p.categoryId)}, ${_text(p.name)}, ${_text(p.description)}, '
          '${_allergens(p.allergens)}, ${p.vegetarian}, ${p.popularity}, '
          '${p.imagePath == null ? 'null' : _text(p.imagePath!)})',
  ];
  out
    ..writeln('${products.join(',\n')};')
    ..writeln()
    ..writeln(
      'insert into public.product_prices (product_id, amount_huf) values',
    );

  final prices = [
    for (final p in demoProducts) '  (${_text(p.id)}, ${p.price.forint})',
  ];
  out
    ..writeln('${prices.join(',\n')};')
    ..writeln()
    ..writeln('-- Stock is not tracked in the demo (null = unlimited).')
    ..writeln(
      'insert into public.inventory (product_id) select id from public.products;',
    );

  return out.toString();
}

void main(List<String> args) {
  final sql = catalogSeedSql();
  if (args.isEmpty) {
    stdout.write(sql);
  } else {
    File(args.first).writeAsStringSync(sql);
  }
}
