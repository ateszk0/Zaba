#!/usr/bin/env python3
"""Builds the product photos from tool/images/selection.json.

    pip install pillow
    python -I tool/images/build_images.py

For every selected Wikimedia Commons file it
  * downloads a 1000 px version,
  * crops it to 4:3 around the centre and saves it as an 800x600 WebP in
    app/assets/images/products/<product-id>.webp,
  * records title, author, licence and source in tool/images/credits.json,
  * regenerates docs/image-credits.md and the credits list the app shows
    (app/lib/features/catalog/data/image_credits.dart).

Only CC0, public domain and CC BY photos are accepted (see commons.py).
"""

import io
import json
import re
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import commons  # noqa: E402

SELECTION = HERE / "selection.json"
CREDITS = HERE / "credits.json"
OUT_DIR = ROOT / "app" / "assets" / "images" / "products"
DOC = ROOT / "docs" / "image-credits.md"
DART = ROOT / "app" / "lib" / "features" / "catalog" / "data" / "image_credits.dart"
SIZE = (800, 600)


def crop_to_ratio(image, ratio):
    width, height = image.size
    if width / height > ratio:
        new_width = round(height * ratio)
        left = (width - new_width) // 2
        return image.crop((left, 0, left + new_width, height))
    new_height = round(width / ratio)
    top = (height - new_height) // 2
    return image.crop((0, top, width, top + new_height))


def clean(text):
    return re.sub(r"\s+", " ", text).strip()


def dart_string(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main():
    selection = json.loads(SELECTION.read_text())
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    credits = {}
    for product_id, title in sorted(selection.items()):
        info = commons.file_info(title)
        if not commons.ACCEPTED_LICENSES.match(info["license"]):
            sys.exit(f"{product_id}: licence {info['license']!r} of {title} is not accepted")
        image = Image.open(io.BytesIO(commons.fetch_bytes(info["thumb_url"]))).convert("RGB")
        image = crop_to_ratio(image, SIZE[0] / SIZE[1]).resize(SIZE, Image.LANCZOS)
        target = OUT_DIR / f"{product_id}.webp"
        image.save(target, "WEBP", quality=78, method=6)
        credits[product_id] = {
            "title": info["title"],
            "page_url": info["page_url"],
            "author": clean(info["author"]) or "ismeretlen",
            "license": info["license"],
            "license_url": info["license_url"],
        }
        print(f"{product_id}: {target.stat().st_size // 1024} KB  {info['license']}")

    CREDITS.write_text(json.dumps(credits, ensure_ascii=False, indent=1, sort_keys=True) + "\n")

    lines = [
        "# Termékfotók forrása és licence",
        "",
        "A demó termékfotói a [Wikimedia Commonsból](https://commons.wikimedia.org/) származnak. Csak **CC0, közkincs és CC BY** licencű",
        "képek kerülhetnek ide (a share-alike, non-commercial és no-derivatives licencűek nem). A képeket 4:3 arányra vágtuk és átméreteztük.",
        "A CC BY licenc névjelzést követel: az app is megjeleníti ezt a listát (Profil, Képek forrásai).",
        "",
        "A listát a `tool/images/build_images.py` generálja a `tool/images/selection.json` alapján; ne szerkeszd kézzel.",
        "A licenc-adatok a Commons API-ból származnak, ellenőrzött adatok, de nem jogi tanács.",
        "",
        "| Termék | Fotó | Szerző | Licenc |",
        "|---|---|---|---|",
    ]
    for product_id, c in sorted(credits.items()):
        name = c["title"].removeprefix("File:")
        license_link = f"[{c['license']}]({c['license_url']})" if c["license_url"] else c["license"]
        lines.append(f"| `{product_id}` | [{name}]({c['page_url']}) | {c['author']} | {license_link} |")
    DOC.write_text("\n".join(lines) + "\n")

    dart = [
        "// GENERATED by tool/images/build_images.py. Do not edit by hand.",
        "// Source and licence of every product photo (shown in the app).",
        "",
        "class ImageCredit {",
        "  const ImageCredit({",
        "    required this.productId,",
        "    required this.title,",
        "    required this.author,",
        "    required this.license,",
        "    required this.pageUrl,",
        "  });",
        "",
        "  final String productId;",
        "  final String title;",
        "  final String author;",
        "  final String license;",
        "  final String pageUrl;",
        "}",
        "",
        "const imageCredits = [",
    ]
    for product_id, c in sorted(credits.items()):
        dart += [
            "  ImageCredit(",
            f"    productId: {dart_string(product_id)},",
            f"    title: {dart_string(c['title'].removeprefix('File:'))},",
            f"    author: {dart_string(c['author'])},",
            f"    license: {dart_string(c['license'])},",
            f"    pageUrl: {dart_string(c['page_url'])},",
            "  ),",
        ]
    dart.append("];")
    DART.write_text("\n".join(dart) + "\n")


if __name__ == "__main__":
    main()
